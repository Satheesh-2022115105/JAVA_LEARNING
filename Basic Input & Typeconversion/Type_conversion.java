package day.day1;

public class Type_conversion {
    public static void main(String[] args) {
        int num1=10;
        double num2=num1;
        System.out.println(num2);

        int num3=(int)10.6789;
        System.out.println(num3);

        int char1=65;
        char ch=(char)char1;
        System.out.println(ch);

        float f1=6.7f;
        double d=f1;
        System.out.println(d);

        long a=num3;
        System.out.println(a);




    }
}
